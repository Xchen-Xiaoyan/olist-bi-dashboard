"""Run sql/analysis.sql against the model and print/save every result (docs/analysis_results.md)."""
import re
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "data" / "model"


def main():
    c = duckdb.connect()
    for f in MODEL.glob("*.csv"):
        c.execute(f"create view {f.stem} as select * from read_csv_auto('{f.as_posix()}', header=true)")
    sql = (ROOT / "sql" / "analysis.sql").read_text(encoding="utf-8")
    blocks = re.split(r"^-- name: (\w+)\s*$", sql, flags=re.M)[1:]
    out = ["# Analysis results\n", "Generated by `scripts/analyze.py` from `sql/analysis.sql`.\n"]
    for name, body in zip(blocks[::2], blocks[1::2]):
        df = c.sql(body).df()
        md = df.head(25).to_markdown(index=False, floatfmt=".3f")
        out += [f"## {name}\n", md, ""]
        print(f"\n== {name}\n{md}")
    (ROOT / "docs" / "analysis_results.md").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
